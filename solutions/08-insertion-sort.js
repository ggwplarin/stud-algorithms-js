// ── Задача 1. Сортировка вставками ─────────────────────────────────────────
//
// Условие: Реализовать сортировку вставками по возрастанию.
//
// Левая часть массива всегда упорядочена. Очередной элемент запоминается, а
// бо́льшие элементы слева от него сдвигаются на одну позицию вправо, пока не
// освободится место для вставки.
//
// Равные элементы не перескакивают друг через друга, поэтому сортировка
// устойчива. На почти упорядоченных данных сдвигов мало, и алгоритм работает
// быстро.
//
// Пример: insertionSort([5, 2, 9, 1, 5, 6]) → [1, 2, 5, 5, 6, 9]

function insertionSort(values) {
  const a = [...values];
  for (let i = 1; i < a.length; i++) {
    const value = a[i];
    let j = i - 1;
    while (j >= 0 && a[j] > value) {
      a[j + 1] = a[j];
      j--;
    }
    a[j + 1] = value;
  }
  return a;
}

