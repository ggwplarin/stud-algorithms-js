// ── Задача 1. Сортировка выбором ───────────────────────────────────────────
//
// Условие: Реализовать сортировку выбором по возрастанию.
//
// На i-м шаге среди ещё не упорядоченных элементов (от i до конца) ищется
// минимальный, и он ставится на позицию i. После шага i первые i + 1
// элементов стоят на своих местах.
//
// В отличие от пузырька, на каждом шаге выполняется не больше одного обмена,
// зато сравнений всегда около n²/2, как бы ни были упорядочены данные.
//
// Пример: selectionSort([5, 2, 9, 1, 5, 6]) → [1, 2, 5, 5, 6, 9]

function selectionSort(values) {
  const a = [...values];
  for (let i = 0; i < a.length; i++) {
    let minimum = i;
    for (let j = i + 1; j < a.length; j++) {
      if (a[j] < a[minimum]) minimum = j;
    }
    [a[i], a[minimum]] = [a[minimum], a[i]];
  }
  return a;
}

