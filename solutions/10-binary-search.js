'use strict';

// ── Задача 1. Бинарный поиск ───────────────────────────────────────────────
//
// Условие: Реализовать бинарный поиск элемента в упорядоченном массиве.
// Вернуть индекс элемента или −1, если его нет.
//
// Поиск хранит границы диапазона `lo` и `hi`, в котором ещё может находиться
// элемент. На каждом шаге он сравнивает искомое значение со средним элементом
// и отбрасывает ту половину, где элемента быть не может: массив упорядочен,
// значит, всё левее середины меньше, а всё правее — больше.
//
// Диапазон уменьшается вдвое за шаг, поэтому миллион элементов
// просматривается примерно за 20 сравнений. Если границы сошлись, а элемент
// не найден, возвращается −1.
//
// Пример: binarySearch([1, 3, 5, 7, 9, 11], 7) → 3

function binarySearch(a, value) {
  let lo = 0;
  let hi = a.length - 1;
  while (lo <= hi) {
    const mid = Math.floor((lo + hi) / 2);
    if (a[mid] === value) return mid;
    if (a[mid] < value) lo = mid + 1;
    else hi = mid - 1;
  }
  return -1;
}

