'use strict';

// ── Задача 1. Площадь и периметр прямоугольника ────────────────────────────
//
// Условие: Даны стороны прямоугольника a и b. Найти его площадь S = a·b и
// периметр P = 2·(a + b).
//
// Задача сводится к двум формулам из условия, поэтому решение линейное: ни
// ветвлений, ни циклов. Функция возвращает оба значения сразу — площадь и
// периметр, — чтобы результат можно было проверить одним вызовом.
//
// Пример: rectangle(3, 4) → [12, 14]

function rectangle(a, b) {
  const area = a * b;
  const perimeter = 2 * (a + b);
  return [area, perimeter];
}

// ── Задача 2. Длина окружности ─────────────────────────────────────────────
//
// Условие: Дан диаметр окружности d. Найти её длину L = π·d, π = 3.14.
//
// Длина окружности — это π, умноженное на диаметр. Значение π взято равным
// 3.14, как требует условие, а не `Math.PI`: так ответ совпадёт с ручным
// расчётом.
//
// Пример: circumference(10) → 31.4

function circumference(d) {
  const PI = 3.14;
  return PI * d;
}

// ── Задача 3. Среднее арифметическое ───────────────────────────────────────
//
// Условие: Даны два числа a и b. Найти их среднее арифметическое (a + b) / 2.
//
// Среднее арифметическое двух чисел — их сумма, делённая пополам. Скобки
// важны: без них на два делилось бы только второе слагаемое.
//
// Пример: average(3, 8) → 5.5

function average(a, b) {
  return (a + b) / 2;
}

// ── Задача 4. Действия с квадратами ────────────────────────────────────────
//
// Условие: Даны два ненулевых числа. Найти сумму, разность, произведение и
// частное их квадратов.
//
// Квадраты вычисляются один раз и сохраняются в переменные `x` и `y`, а затем
// все четыре действия выполняются уже над ними. Это короче и избавляет от
// повторных умножений. Числа по условию ненулевые, поэтому деление безопасно.
//
// Пример: squares(2, -4) → [20, -12, 64, 0.25]

function squares(a, b) {
  const x = a * a;
  const y = b * b;
  return [x + y, x - y, x * y, x / y];
}

// ── Задача 5. Действия с модулями ──────────────────────────────────────────
//
// Условие: Даны два ненулевых числа. Найти сумму, разность, произведение и
// частное их модулей.
//
// Устроено так же, как предыдущая задача, только вместо квадратов берутся
// модули через `Math.abs`. Модули тоже считаются заранее, чтобы каждое из
// четырёх выражений читалось как формула.
//
// Пример: moduli(-3, 6) → [9, -3, 18, 0.5]

function moduli(a, b) {
  const x = Math.abs(a);
  const y = Math.abs(b);
  return [x + y, x - y, x * y, x / y];
}

// ── Задача 6. Расстояние между точками ─────────────────────────────────────
//
// Условие: Найти расстояние между точками (x1, y1) и (x2, y2).
//
// Расстояние между точками — гипотенуза прямоугольного треугольника с
// катетами `x2 − x1` и `y2 − y1`. `Math.hypot` вычисляет √(a² + b²) напрямую,
// и формула Пифагора видна в коде без лишних скобок.
//
// Пример: distance(0, 0, 3, 4) → 5

function distance(x1, y1, x2, y2) {
  return Math.hypot(x2 - x1, y2 - y1);
}

// ── Задача 7. Отрезки на числовой оси ──────────────────────────────────────
//
// Условие: Даны точки A, B, C на числовой оси. Найти длины отрезков AC и BC и
// их сумму.
//
// На числовой оси длина отрезка равна модулю разности координат его концов.
// Модуль нужен, потому что заранее неизвестно, какая из точек лежит левее.
//
// Пример: segments(-2, 5, 1) → [3, 4, 7]

function segments(a, b, c) {
  const ac = Math.abs(a - c);
  const bc = Math.abs(b - c);
  return [ac, bc, ac + bc];
}

// ── Задача 8. Произведение отрезков ────────────────────────────────────────
//
// Условие: Точка C лежит между точками A и B на числовой оси. Найти
// произведение длин отрезков AC и BC.
//
// Точка C лежит между A и B, так что длины AC и BC снова находятся как модули
// разностей, после чего остаётся их перемножить.
//
// Пример: segmentsProduct(-2, 5, 1) → 12

function segmentsProduct(a, b, c) {
  return Math.abs(a - c) * Math.abs(b - c);
}

// ── Задача 9. Прямоугольник по двум вершинам ───────────────────────────────
//
// Условие: Даны противоположные вершины (x1, y1) и (x2, y2) прямоугольника со
// сторонами, параллельными осям. Найти периметр и площадь.
//
// Стороны прямоугольника параллельны осям, поэтому ширина равна разности
// абсцисс противоположных вершин, а высота — разности ординат, обе по модулю.
// Дальше применяются обычные формулы периметра и площади.
//
// Пример: rectangleByCorners(1, 1, 4, 3) → [10, 6]

function rectangleByCorners(x1, y1, x2, y2) {
  const width = Math.abs(x2 - x1);
  const height = Math.abs(y2 - y1);
  return [2 * (width + height), width * height];
}

// ── Задача 10. Периметр и площадь треугольника ─────────────────────────────
//
// Условие: Даны вершины треугольника (x1, y1), (x2, y2), (x3, y3). Найти его
// периметр и площадь.
//
// Периметр — сумма трёх сторон, каждая из которых считается как расстояние
// между вершинами (см. задачу 6).
//
// Для площади удобнее формула через векторное произведение: модуль выражения
// `(x2 − x1)(y3 − y1) − (x3 − x1)(y2 − y1)` равен площади параллелограмма на
// двух сторонах треугольника, а треугольник — его половина. В отличие от
// формулы Герона, здесь нет корней и погрешностей округления.
//
// Пример: triangle(0, 0, 3, 0, 0, 4) → [12, 6]

function triangle(x1, y1, x2, y2, x3, y3) {
  const perimeter =
    Math.hypot(x2 - x1, y2 - y1) +
    Math.hypot(x3 - x2, y3 - y2) +
    Math.hypot(x1 - x3, y1 - y3);
  // Площадь через векторное произведение сторон.
  const area = Math.abs((x2 - x1) * (y3 - y1) - (x3 - x1) * (y2 - y1)) / 2;
  return [perimeter, area];
}

// ── Задача 11. Значение функции 3x⁶ − 6x² − 7 ──────────────────────────────
//
// Условие: Найти значение функции y = 3x⁶ − 6x² − 7 при данном x.
//
// Значение многочлена при заданном x вычисляется прямо по формуле, оператор
// `**` обозначает степень.
//
// Пример: f(2) → 161

function f(x) {
  return 3 * x ** 6 - 6 * x ** 2 - 7;
}

// ── Задача 12. Значение функции 4(x−3)⁶ − 7(x−3)³ + 2 ──────────────────────
//
// Условие: Найти значение функции y = 4(x − 3)⁶ − 7(x − 3)³ + 2 при данном x.
//
// Выражение `x − 3` встречается дважды, поэтому оно вынесено в переменную
// `t`. Формула становится короче и превращается в многочлен от `t`, который
// легко сверить с условием.
//
// Пример: g(5) → 202

function g(x) {
  const t = x - 3;
  return 4 * t ** 6 - 7 * t ** 3 + 2;
}

