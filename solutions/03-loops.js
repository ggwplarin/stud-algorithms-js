'use strict';

// ── Задача 1. Стоимость конфет ─────────────────────────────────────────────
//
// Условие: Дано вещественное число — цена 1 кг конфет. Вывести стоимость 0.1,
// 0.2, ..., 1 кг конфет.
//
// Цикл проходит десять шагов, по 0.1 кг каждый. Масса вычисляется как `i /
// 10` от номера шага, а не накапливается сложением, потому что многократное
// прибавление 0.1 даёт накопленную ошибку округления.
//
// Пример: candyCosts(50) → [5, 10, 15, 20, 25, 30, 35, 40, 45, 50]

function candyCosts(price) {
  const costs = [];
  for (let i = 1; i <= 10; i++) {
    costs.push(price * i / 10);
  }
  return costs;
}

// ── Задача 2. Произведение 1.1 · 1.2 · 1.3 · ... ───────────────────────────
//
// Условие: Дано целое число N (> 0). Найти произведение 1.1 · 1.2 · 1.3 · ...
// (N сомножителей).
//
// Сомножители 1.1, 1.2, 1.3… выражаются через номер шага как `1 + i / 10`.
// Произведение накапливается в переменной, начальное значение которой равно 1
// — нейтральному элементу умножения.
//
// Пример: productOfFactors(3) → 1.716

function productOfFactors(n) {
  let product = 1;
  for (let i = 1; i <= n; i++) {
    product *= 1 + i / 10;
  }
  return product;
}

// ── Задача 3. Квадрат числа через сумму нечётных ───────────────────────────
//
// Условие: Дано целое число N (> 0). Найти квадрат числа по формуле N² = 1 +
// 3 + 5 + ... + (2·N − 1). После добавления каждого слагаемого выводить
// текущее значение суммы.
//
// Сумма первых N нечётных чисел равна N², и программа показывает это
// наглядно: на каждом шаге прибавляется очередное нечётное число `2i + 1`, а
// текущая сумма сохраняется. Последний элемент результата — искомый квадрат.
//
// Пример: squareBySum(4) → [1, 4, 9, 16]

function squareBySum(n) {
  let sum = 0;
  const partialSums = [];
  for (let i = 0; i < n; i++) {
    sum += 2 * i + 1;
    partialSums.push(sum);
  }
  return partialSums;
}

// ── Задача 4. Сумма 1 + A + A² + ... + Aᴺ ──────────────────────────────────
//
// Условие: Дано вещественное число A и целое число N (> 0). Используя один
// цикл, найти сумму 1 + A + A² + A³ + ... + Aᴺ.
//
// Условие требует одного цикла, поэтому степень не пересчитывается заново на
// каждом шаге, а получается из предыдущей умножением на A. Так каждая
// итерация выполняет одно умножение и одно сложение.
//
// Пример: powerSum(2, 3) → 15

function powerSum(a, n) {
  let sum = 1;
  let power = 1;
  for (let i = 0; i < n; i++) {
    power *= a;
    sum += power;
  }
  return sum;
}

// ── Задача 5. Знакопеременная сумма ────────────────────────────────────────
//
// Условие: Дано вещественное число A и целое число N (> 0). Используя один
// цикл, найти значение выражения 1 − A + A² − A³ + ... ± Aᴺ. Условный
// оператор не использовать.
//
// Здесь та же схема, что и в предыдущей задаче, но условный оператор
// запрещён. Знак чередуется сам, если умножать на −A: тогда чётные степени
// положительны, нечётные — отрицательны.
//
// Пример: alternatingSum(2, 3) → -5

function alternatingSum(a, n) {
  let sum = 1;
  let power = 1;
  for (let i = 0; i < n; i++) {
    power *= -a; // знак меняется сам, условие не нужно
    sum += power;
  }
  return sum;
}

// ── Задача 6. Числа от A до B с повторениями ───────────────────────────────
//
// Условие: Даны целые положительные числа A и B (A < B). Вывести все целые
// числа от A до B включительно; каждое число выводится столько раз, каково
// его значение.
//
// Два вложенных цикла: внешний перебирает числа от A до B, внутренний
// добавляет текущее число столько раз, какое оно по величине.
//
// Пример: repeatedNumbers(2, 4) → [2, 2, 3, 3, 3, 4, 4, 4, 4]

function repeatedNumbers(a, b) {
  const result = [];
  for (let number = a; number <= b; number++) {
    for (let times = 0; times < number; times++) {
      result.push(number);
    }
  }
  return result;
}

// ── Задача 7. Незанятая часть отрезка ──────────────────────────────────────
//
// Условие: Даны положительные числа A и B (A > B). На отрезке длины A
// размещено максимально возможное количество отрезков длины B без наложений.
// Не используя умножение и деление, найти длину незанятой части.
//
// Умножать и делить нельзя, поэтому отрезки «укладываются» по одному: из
// длины A вычитается B, пока остаток не станет меньше B. То, что осталось, и
// есть незанятая часть. По сути это деление с остатком через вычитание.
//
// Пример: freeLength(10, 3) → 1

function freeLength(a, b) {
  if (!(a > b && b > 0)) {
    throw new Error('Требуется A > B > 0');
  }
  let rest = a;
  while (rest >= b) {
    rest -= b; // убираем по одному отрезку длины B
  }
  return rest;
}

// ── Задача 8. Наименьшее K с суммой 1 + ... + K ≥ N ────────────────────────
//
// Условие: Дано целое число N (> 1). Вывести наименьшее целое K, для которого
// сумма 1 + 2 + ... + K больше или равна N, и саму эту сумму.
//
// Заранее неизвестно, сколько слагаемых понадобится, поэтому используется
// цикл `while`. K и сумма растут вместе, и цикл останавливается, как только
// сумма впервые достигнет N. Именно поэтому найденное K наименьшее.
//
// Пример: smallestK(10) → [4, 10]

function smallestK(n) {
  let k = 0;
  let sum = 0;
  while (sum < n) {
    k += 1;
    sum += k;
  }
  return [k, sum];
}

// ── Задача 9. Банковский вклад ─────────────────────────────────────────────
//
// Условие: Начальный вклад равен 1000 руб. Каждый месяц вклад увеличивается
// на P процентов (0 < P < 25). Определить, через сколько месяцев K вклад
// превысит 1100 руб., и вывести K и итоговый размер вклада S.
//
// Число месяцев заранее неизвестно, поэтому цикл продолжается, пока вклад не
// превысит 1100 руб. Каждый месяц сумма умножается на `1 + P/100` — это рост
// на P процентов с капитализацией.
//
// Пример: depositMonths(10) → [2, 1210]

function depositMonths(p) {
  if (!(p > 0 && p < 25)) {
    throw new Error('Требуется 0 < P < 25');
  }
  let months = 0;
  let sum = 1000;
  while (sum <= 1100) {
    sum *= 1 + p / 100;
    months += 1;
  }
  return [months, sum];
}

// ── Задача 10. НОД (алгоритм Евклида) ──────────────────────────────────────
//
// Условие: Даны целые положительные числа A и B. Найти их наибольший общий
// делитель, используя алгоритм Евклида.
//
// Алгоритм Евклида основан на том, что НОД(a, b) = НОД(b, a mod b). Пара
// чисел заменяется на (b, остаток) до тех пор, пока остаток не станет нулём;
// тогда оставшееся число и есть наибольший общий делитель. Остаток
// уменьшается очень быстро, поэтому шагов немного.
//
// Пример: gcd(48, 18) → 6

function gcd(a, b) {
  while (b !== 0) {
    const remainder = a % b;
    a = b;
    b = remainder;
  }
  return a;
}

