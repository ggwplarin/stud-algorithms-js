'use strict';

// ── Задача 1. Первые нечётные числа ────────────────────────────────────────
//
// Условие: Дано целое число N (> 0). Сформировать и вывести целочисленный
// массив размера N, содержащий N первых положительных нечётных чисел: 1, 3,
// 5, …
//
// k-е нечётное число (счёт с нуля) равно `2k + 1`, поэтому массив строится
// сразу по формуле. `Array.from` создаёт массив длины N и заполняет его
// значением, зависящим от индекса.
//
// Пример: firstOddNumbers(3) → [1, 3, 5]

function firstOddNumbers(n) {
  // i-е нечётное число (с нуля) равно 2i + 1
  return Array.from({ length: n }, (_, i) => 2 * i + 1);
}

// ── Задача 2. Геометрическая прогрессия ────────────────────────────────────
//
// Условие: Дано целое число N (> 1), а также первый член A и знаменатель D
// геометрической прогрессии. Сформировать и вывести массив размера N,
// содержащий N первых членов прогрессии: A, A·D, A·D², A·D³, …
//
// Член геометрической прогрессии с индексом i равен A · Dⁱ. Массив
// заполняется по этой формуле так же, как в предыдущей задаче.
//
// Пример: geometricProgression(4, 2, 3) → [2, 6, 18, 54]

function geometricProgression(n, a, d) {
  return Array.from({ length: n }, (_, i) => a * d ** i);
}

// ── Задача 3. Сумма всех предыдущих ────────────────────────────────────────
//
// Условие: Даны целые числа N (> 2), A и B. Сформировать и вывести
// целочисленный массив размера N, первый элемент которого равен A, второй
// равен B, а каждый последующий элемент равен сумме всех предыдущих.
//
// Каждый следующий элемент равен сумме всех предыдущих, а значит, сразу после
// его добавления общая сумма удваивается. Поэтому хранить и пересуммировать
// весь массив не нужно: достаточно одной переменной `total`, которая каждый
// раз удваивается.
//
// Пример: sumOfPrevious(5, 1, 2) → [1, 2, 3, 6, 12]

function sumOfPrevious(n, a, b) {
  const result = [a, b];
  let total = a + b;
  while (result.length < n) {
    result.push(total);
    total += total;
  }
  return result;
}

// ── Задача 4. Чередование с концов ─────────────────────────────────────────
//
// Условие: Дан массив A размера N. Вывести его элементы в следующем порядке:
// A1, AN, A2, AN−1, A3, AN−2, …
//
// Два указателя идут навстречу друг другу, с начала и с конца массива, и по
// очереди забирают элементы. Проверка `left <= right` внутри цикла нужна для
// массивов нечётной длины: средний элемент берётся только один раз.
//
// Пример: alternateEnds([1, 2, 3, 4, 5]) → [1, 5, 2, 4, 3]

function alternateEnds(a) {
  const result = [];
  let left = 0;
  let right = a.length - 1;
  while (left <= right) {
    result.push(a[left]);
    left++;
    if (left <= right) {
      result.push(a[right]);
      right--;
    }
  }
  return result;
}

// ── Задача 5. Нечётные и чётные номера ─────────────────────────────────────
//
// Условие: Дан массив A размера N. Вывести вначале его элементы с нечётными
// номерами в порядке возрастания номеров, а затем — элементы с чётными
// номерами в порядке убывания номеров.
//
// Номера в условии начинаются с 1, а индексы в JavaScript — с 0. Значит,
// элементам с нечётными номерами соответствуют чётные индексы.
//
// Массив делится фильтром на две части, а вторая разворачивается, потому что
// элементы с чётными номерами нужны в порядке убывания.
//
// Пример: oddThenEvenPositions([1, 2, 3, 4, 5]) → [1, 3, 5, 4, 2]

function oddThenEvenPositions(a) {
  // номера с 1: нечётным номерам соответствуют чётные индексы
  const oddPositions = a.filter((_, i) => i % 2 === 0);
  const evenPositions = a.filter((_, i) => i % 2 === 1);
  return [...oddPositions, ...evenPositions.reverse()];
}

// ── Задача 6. Среднее на отрезке ───────────────────────────────────────────
//
// Условие: Дан массив размера N и целые числа K и L (1 ≤ K ≤ L ≤ N). Найти
// среднее арифметическое элементов массива с номерами от K до L включительно.
//
// Нужный отрезок вырезается методом `slice`: номера K…L соответствуют
// индексам K − 1…L − 1, а правая граница в `slice` не включается. Затем сумма
// делится на длину отрезка.
//
// Пример: averageOnRange([1, 2, 3, 4, 5], 2, 4) → 3

function averageOnRange(a, k, l) {
  const range = a.slice(k - 1, l);
  const sum = range.reduce((total, x) => total + x, 0);
  return sum / range.length;
}

// ── Задача 7. Арифметическая прогрессия ────────────────────────────────────
//
// Условие: Дан целочисленный массив размера N, не содержащий одинаковых
// чисел. Проверить, образуют ли его элементы арифметическую прогрессию. Если
// образуют, то вывести разность прогрессии, если нет — вывести 0.
//
// Разность прогрессии определяется по первым двум элементам. Затем
// проверяется, что все остальные соседние пары дают ту же разность. При
// первом несовпадении ответ уже известен, и цикл прерывается.
//
// Пример: progressionDifference([1, 3, 5]) → 2

function progressionDifference(a) {
  if (a.length < 2) {
    throw new Error('Нужно минимум два элемента');
  }
  const diff = a[1] - a[0];
  for (let i = 2; i < a.length; i++) {
    if (a[i] - a[i - 1] !== diff) {
      return 0;
    }
  }
  return diff;
}

// ── Задача 8. Минимум среди чётных номеров ─────────────────────────────────
//
// Условие: Дан массив A размера N. Найти минимальный элемент из его элементов
// с чётными номерами: A2, A4, A6, …
//
// Элементы с чётными номерами (A2, A4, …) соответствуют нечётным индексам.
// Они отбираются фильтром, и среди них ищется минимум. Если массив короче
// двух элементов, таких элементов нет, и функция сообщает об этом.
//
// Пример: minAtEvenPositions([5, 2, 7, 1]) → 1

function minAtEvenPositions(a) {
  if (a.length < 2) {
    throw new Error('Нет элементов с чётными номерами');
  }
  const evenPositions = a.filter((_, i) => i % 2 === 1);
  return Math.min(...evenPositions);
}

// ── Задача 9. Последний локальный максимум ─────────────────────────────────
//
// Условие: Дан массив размера N. Найти номер его последнего локального
// максимума (локальный максимум — это элемент, который больше любого из своих
// соседей). Крайние элементы сравниваются с единственным соседом; если
// максимума нет, вывести 0.
//
// Нужен последний локальный максимум, поэтому массив просматривается с конца,
// и первое найденное совпадение сразу становится ответом. У крайних элементов
// только один сосед, и сравнение идёт с ним.
//
// Пример: lastLocalMaximum([1, 3, 2, 5, 4]) → 4

function lastLocalMaximum(a) {
  for (let i = a.length - 1; i >= 0; i--) {
    const biggerThanLeft = i === 0 || a[i] > a[i - 1];
    const biggerThanRight = i === a.length - 1 || a[i] > a[i + 1];
    if (biggerThanLeft && biggerThanRight) {
      return i + 1;
    }
  }
  return 0;
}

// ── Задача 10. Номера одинаковых элементов ─────────────────────────────────
//
// Условие: Дан целочисленный массив размера N, содержащий ровно два
// одинаковых элемента. Найти номера одинаковых элементов и вывести эти номера
// в порядке возрастания.
//
// Номера уже просмотренных значений запоминаются в `Map`. Как только значение
// встречается повторно, оба номера известны: первый берётся из `Map`, второй
// — текущий. Массив проходится один раз, а номера получаются уже
// упорядоченными.
//
// Пример: findDuplicatePositions([4, 1, 2, 1]) → [2, 4]

function findDuplicatePositions(a) {
  const seen = new Map();
  for (let i = 0; i < a.length; i++) {
    if (seen.has(a[i])) {
      return [seen.get(a[i]), i + 1];
    }
    seen.set(a[i], i + 1);
  }
  throw new Error('Повтор не найден');
}

