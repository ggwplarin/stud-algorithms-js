'use strict';

// ── Задача 1. Факториал ────────────────────────────────────────────────────
//
// Условие: Напишите функцию, которая рекурсивно вычисляет факториал числа n.
//
// Факториал определяется рекурсивно: n! = n · (n − 1)!, а 0! = 1! = 1 служат
// базой рекурсии. Для отрицательного n факториал не определён, и функция
// сообщает об ошибке.
//
// Пример: factorial(5) → 120

function factorial(n) {
  if (n < 0) {
    throw new Error('n должно быть неотрицательным');
  }
  return n < 2 ? 1 : n * factorial(n - 1);
}

// ── Задача 2. Числа Фибоначчи ──────────────────────────────────────────────
//
// Условие: Напишите функцию, которая рекурсивно вычисляет n-е число Фибоначчи
// (F₀ = 0, F₁ = 1).
//
// Прямолинейная рекурсия F(n) = F(n − 1) + F(n − 2) вычисляет одни и те же
// значения много раз и растёт экспоненциально. Поэтому вспомогательная
// функция `step` передаёт в рекурсивный вызов пару соседних чисел и сдвигает
// её на один шаг вперёд. Решение остаётся рекурсивным, но выполняет только n
// вызовов.
//
// Начальные значения F₀ = 0 и F₁ = 1 заданы условием.
//
// Пример: fibonacci(10) → 55

function fibonacci(n) {
  if (n < 0) {
    throw new Error('n должно быть неотрицательным');
  }
  // k шагов осталось, a и b — два соседних числа
  function step(k, a, b) {
    return k === 0 ? a : step(k - 1, b, a + b);
  }
  return step(n, 0, 1);
}

// ── Задача 3. Возведение в степень ─────────────────────────────────────────
//
// Условие: Напишите функцию, которая рекурсивно возводит число x в целую
// степень n.
//
// Степень сводится к меньшей степени: xⁿ = x · xⁿ⁻¹, база рекурсии — x⁰ = 1.
// Отрицательная степень обрабатывается через обратное число: x⁻ⁿ = 1 / xⁿ.
//
// Пример: power(2, 10) → 1024

function power(x, n) {
  if (n < 0) {
    return 1 / power(x, -n);
  }
  return n === 0 ? 1 : x * power(x, n - 1);
}

// ── Задача 4. Палиндром ────────────────────────────────────────────────────
//
// Условие: Напишите функцию, которая рекурсивно проверяет, является ли строка
// палиндромом.
//
// Строка является палиндромом, если её первый и последний символы совпадают и
// середина тоже палиндром. Строки из нуля или одного символа — база рекурсии.
// Регистр и пробелы не игнорируются, поэтому строка сравнивается в точности
// как задана.
//
// Пример: isPalindrome('шалаш') → true

function isPalindrome(text) {
  if (text.length < 2) {
    return true;
  }
  // сравниваем крайние символы и проверяем середину
  return text[0] === text[text.length - 1] && isPalindrome(text.slice(1, -1));
}

// ── Задача 5. Бинарный поиск ───────────────────────────────────────────────
//
// Условие: Напишите функцию, которая рекурсивно выполняет бинарный поиск
// элемента в отсортированном массиве. Результат — индекс с нуля или −1.
//
// Каждый вызов смотрит на средний элемент текущего диапазона `[low, high]`.
// Если искомое значение меньше, поиск продолжается в левой половине, иначе —
// в правой. Диапазон каждый раз сокращается вдвое, так что вызовов будет
// порядка log₂ n.
//
// Пустой диапазон (`low > high`) означает, что элемента нет, и функция
// возвращает −1.
//
// Пример: binarySearch([1, 3, 5, 7, 9], 7) → 3

function binarySearch(items, value, low = 0, high = items.length - 1) {
  if (low > high) {
    return -1;
  }
  const middle = Math.floor((low + high) / 2);
  if (items[middle] === value) {
    return middle;
  }
  return value < items[middle]
    ? binarySearch(items, value, low, middle - 1)
    : binarySearch(items, value, middle + 1, high);
}

// ── Задача 6. Обратный порядок слов ────────────────────────────────────────
//
// Условие: Напишите функцию, которая рекурсивно меняет порядок слов в строке
// на обратный.
//
// Строка разбивается на слова, после чего рекурсивно переворачивается список:
// перевёрнутый хвост, а за ним первое слово. Пустые элементы, которые
// появляются при двойных пробелах, отбрасываются.
//
// Пример: reverseWords('один два три') → 'три два один'

function reverseWords(text) {
  const words = text.split(' ').filter((word) => word.length > 0);
  function reverse(list) {
    return list.length < 2 ? list : reverse(list.slice(1)).concat(list.slice(0, 1));
  }
  return reverse(words).join(' ');
}

// ── Задача 7. Разложение на простые слагаемые ──────────────────────────────
//
// Условие: Напишите функцию, которая рекурсивно разлагает число n на сумму
// простых чисел (одно разложение, повторения допускаются).
//
// Любое целое число n ≥ 2 раскладывается в сумму двоек и, если n нечётно,
// одной тройки, а 2 и 3 — простые. Поэтому рекурсия отнимает двойку, пока не
// останется 2 или 3. Условие требует одно любое разложение, и это самое
// простое.
//
// Пример: primeSummands(10) → [2, 2, 2, 2, 2]

function primeSummands(n) {
  if (n < 2) {
    throw new Error('n должно быть не меньше 2');
  }
  if (!Number.isInteger(n)) {
    return null;
  }
  if (n <= 3) {
    return [n];
  }
  // Любое целое n >= 2 — сумма двоек и, для нечётного n, одной тройки.
  return [2].concat(primeSummands(n - 2));
}

// ── Задача 8. Количество цифр ──────────────────────────────────────────────
//
// Условие: Напишите функцию, которая рекурсивно подсчитывает количество цифр
// в числе.
//
// Количество цифр числа на одну больше, чем у числа без последней цифры.
// Отбросить её можно делением на 10 нацело. Однозначные числа — база
// рекурсии. Знак на число цифр не влияет, поэтому берётся модуль.
//
// Пример: countDigits(12345) → 5

function countDigits(n) {
  const absolute = Math.abs(n);
  return absolute < 10 ? 1 : 1 + countDigits(Math.floor(absolute / 10));
}

// ── Задача 9. Ханойская башня ──────────────────────────────────────────────
//
// Условие: Напишите рекурсивное решение головоломки «Ханойская башня»:
// выведите список ходов переноса n дисков со стержня A на стержень C через B.
//
// Чтобы перенести n дисков с A на C, нужно перенести n − 1 верхних дисков на
// вспомогательный стержень B, переложить самый большой диск на C и вернуть n
// − 1 дисков с B на C. Для меньших башен действует то же правило, а ноль
// дисков не требует ходов.
//
// Всего получается 2ⁿ − 1 ход — меньше сделать нельзя.
//
// Пример: hanoi(2) → ['A → B', 'A → C', 'B → C']

function hanoi(n, source = 'A', target = 'C', spare = 'B') {
  if (n < 0) {
    throw new Error('n должно быть неотрицательным');
  }
  if (n === 0) {
    return [];
  }
  return hanoi(n - 1, source, spare, target)
    .concat([source + ' → ' + target])
    .concat(hanoi(n - 1, spare, target, source));
}

