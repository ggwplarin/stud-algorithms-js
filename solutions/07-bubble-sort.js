// ── Задача 1. Сортировка пузырьком ─────────────────────────────────────────
//
// Условие: Реализовать сортировку пузырьком по возрастанию: соседние элементы
// сравниваются и меняются местами, пока массив не станет упорядоченным.
//
// За каждый проход соседние элементы сравниваются и при необходимости
// меняются местами, поэтому наибольший из оставшихся элементов «всплывает» в
// конец. После каждого прохода неупорядоченная часть уменьшается на один
// элемент, и следующий проход её короче.
//
// Если за проход не было ни одного обмена, массив уже упорядочен и сортировку
// можно завершить. Поэтому на упорядоченных данных хватает одного прохода.
// Сортируется копия, исходный массив не меняется.
//
// Пример: bubbleSort([5, 2, 9, 1, 5, 6]) → [1, 2, 5, 5, 6, 9]

function bubbleSort(values) {
  const a = [...values];
  for (let end = a.length - 1; end > 0; end--) {
    let changed = false;
    for (let i = 0; i < end; i++) {
      if (a[i] > a[i + 1]) {
        [a[i], a[i + 1]] = [a[i + 1], a[i]];
        changed = true;
      }
    }
    if (!changed) break; // обменов не было — массив уже упорядочен
  }
  return a;
}

